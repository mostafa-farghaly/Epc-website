/*******************************
 * 2) setLanguage (base)
 *******************************/
function setLanguage(lang) {
  const dict = translations[lang] || translations.en;

  // lang + RTL toggle
  document.documentElement.lang = lang;
  const isRTL = lang === "ar";
  document.body.dir = isRTL ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", isRTL);

  // replace texts in all [data-translate]
  document.querySelectorAll("[data-translate]").forEach((el) => {
    const key = el.getAttribute("data-translate");
    if (dict[key] !== undefined) {
      el.textContent = dict[key];
    } else if (translations.en[key] !== undefined) {
      el.textContent = translations.en[key]; // fallback
      console.warn(`Missing key "${key}" in ${lang}, used EN fallback`);
    } else {
      console.warn(`Unknown translation key: ${key}`);
    }
  });

  localStorage.setItem("selectedLanguage", lang);
}

/*******************************
 * 3) Header Carousel (Owl)
 *******************************/
function initHeaderCarousel() {
  const isRTL = document.body.dir === "rtl";
  const $carousel = $(".header-carousel");

  // destroy safely (do NOT unwrap)
  if ($carousel.hasClass("owl-loaded")) {
    try {
      $carousel.trigger("destroy.owl.carousel");
    } catch (e) {}
  }

  // re-init with correct direction
  $carousel.owlCarousel({
    autoplay: true,
    smartSpeed: 1000,
    items: 1,
    dots: true,
    loop: true,
    nav: true,
    rtl: isRTL,
    navText: ['<i class="fa fa-chevron-left"></i>', '<i class="fa fa-chevron-right"></i>']
  });

  // refresh right away to stabilize first paint
  setTimeout(() => {
    try { $carousel.trigger("refresh.owl.carousel"); } catch (e) {}
  }, 0);
}

/*******************************
 * 4) Bootstrap dropdown helper
 *******************************/
function hideDropdownById(id) {
  const trigger = document.getElementById(id);
  if (!trigger) return;

  try {
    if (window.bootstrap && bootstrap.Dropdown) {
      if (typeof bootstrap.Dropdown.getOrCreateInstance === "function") {
        const dd = bootstrap.Dropdown.getOrCreateInstance(trigger);
        dd.hide();
        return;
      }
      if (typeof bootstrap.Dropdown.getInstance === "function") {
        let dd = bootstrap.Dropdown.getInstance(trigger);
        if (!dd) dd = new bootstrap.Dropdown(trigger);
        dd.hide();
        return;
      }
      const dd = new bootstrap.Dropdown(trigger);
      dd.hide();
      return;
    }
    if (window.jQuery && typeof jQuery.fn.dropdown === "function") {
      jQuery(trigger).dropdown("hide");
    }
  } catch (err) {
    console.warn("Dropdown hide fallback failed:", err);
  }
}

/*******************************
 * 5) Swipers (Services + Clients)
 *    — Correct arrows in LTR/RTL
 *******************************/
window.EPC = window.EPC || {};
EPC.servicesSwiper = EPC.servicesSwiper || null;
EPC.clientsSwiper  = EPC.clientsSwiper  || null;

function initSwipers() {
  // create ONCE
  if (!EPC.servicesSwiper) {
    const servicesEl = document.querySelector(".mySwiper");
    if (servicesEl) {
      servicesEl.setAttribute("dir", document.body.dir === "rtl" ? "rtl" : "ltr");
      EPC.servicesSwiper = new Swiper(servicesEl, {
        direction: "horizontal",
        loop: true,
        watchOverflow: true,
        spaceBetween: 24,
        slidesPerView: 1,
        breakpoints: { 768: { slidesPerView: 2 }, 1200: { slidesPerView: 3 } },
        navigation: {
          nextEl: servicesEl.querySelector(".swiper-button-next"),
          prevEl: servicesEl.querySelector(".swiper-button-prev"),
        },
        pagination: { el: servicesEl.querySelector(".swiper-pagination"), clickable: true },
        observer: true, observeParents: true, observeSlideChildren: true,
      });
    }
  }

  if (!EPC.clientsSwiper) {
    const clientsEl = document.querySelector(".clients-swiper");
    if (clientsEl) {
      clientsEl.setAttribute("dir", document.body.dir === "rtl" ? "rtl" : "ltr");
      EPC.clientsSwiper = new Swiper(clientsEl, {
        direction: "horizontal",
        loop: true,
        watchOverflow: true,
        spaceBetween: 24,
        slidesPerView: 2,
        breakpoints: { 576: { slidesPerView: 3 }, 992: { slidesPerView: 5 } },
        autoplay: { delay: 3000 },
        navigation: {
          nextEl: clientsEl.querySelector(".swiper-button-next"),
          prevEl: clientsEl.querySelector(".swiper-button-prev"),
        },
        observer: true, observeParents: true, observeSlideChildren: true,
      });
    }
  }
}


/*******************************
 * 6) DOM Ready
 *******************************/
document.addEventListener("DOMContentLoaded", () => {
  // language init
  const saved = localStorage.getItem("selectedLanguage") || "en";
  setLanguage(saved);

  // bind language items + close dropdown
  document.querySelectorAll("[data-lang]").forEach((item) => {
    item.addEventListener("click", (e) => {
      e.preventDefault();
      const lang = item.getAttribute("data-lang");
      setLanguage(lang);
      hideDropdownById("languageDropdown");
    });
  });

  // init carousels/sliders
  initHeaderCarousel();
  initSwipers();
});

/*******************************
 * 7) Patch setLanguage once
 *    (rebuild direction-sensitive UI)
 *******************************/
(function () {
  const original = window.setLanguage;
  if (original && original.__patchedForRTL) return;

  window.setLanguage = function (lang) {
    if (typeof original === "function") original(lang); // run base translator
    // re-init things that depend on dir
    try { initHeaderCarousel(); } catch (e) { console.warn(e); }
    try { initSwipers(); } catch (e) { console.warn(e); }
    try { hideDropdownById("languageDropdown"); } catch (e) {}
  };

  window.setLanguage.__patchedForRTL = true;
})();
